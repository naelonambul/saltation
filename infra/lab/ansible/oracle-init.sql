-- Idempotent Saltation storage & schema setup for native Oracle 19c EE (ORCLCDB / ORCLPDB1).
-- Applies spec N-7 / F-36a caps: 3x 1 GB redo, 4 GB undo cap, 2 GB PGA limit,
-- SALTATION_DATA, 4 GB-capped OUTBOX_TS, and the SALTATION schema owner.
WHENEVER SQLERROR EXIT SQL.SQLCODE

ALTER SESSION SET CONTAINER = CDB$ROOT;
ALTER SYSTEM SET sga_target = 3584M SCOPE = SPFILE;
ALTER SYSTEM SET sga_max_size = 3584M SCOPE = SPFILE;
ALTER SYSTEM SET pga_aggregate_limit = 2048M SCOPE = BOTH;
ALTER PLUGGABLE DATABASE ORCLPDB1 SAVE STATE;

DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM v$log WHERE group# = 11;
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE q'[ALTER DATABASE ADD LOGFILE GROUP 11 ('/opt/oracle/oradata/ORCLCDB/redo11.log') SIZE 1G]';
    EXECUTE IMMEDIATE q'[ALTER DATABASE ADD LOGFILE GROUP 12 ('/opt/oracle/oradata/ORCLCDB/redo12.log') SIZE 1G]';
    EXECUTE IMMEDIATE q'[ALTER DATABASE ADD LOGFILE GROUP 13 ('/opt/oracle/oradata/ORCLCDB/redo13.log') SIZE 1G]';
    FOR g IN (SELECT group# FROM v$log WHERE group# < 11) LOOP
      LOOP
        BEGIN
          EXECUTE IMMEDIATE 'ALTER SYSTEM SWITCH LOGFILE';
          EXECUTE IMMEDIATE 'ALTER SYSTEM CHECKPOINT';
          EXECUTE IMMEDIATE 'ALTER DATABASE DROP LOGFILE GROUP ' || g.group#;
          EXIT;
        EXCEPTION WHEN OTHERS THEN
          IF SQLCODE IN (-1623, -1624) THEN DBMS_SESSION.SLEEP(1); ELSE RAISE; END IF;
        END;
      END LOOP;
    END LOOP;
  END IF;
END;
/

BEGIN
  FOR f IN (SELECT file_name FROM dba_data_files WHERE tablespace_name LIKE 'UNDOTBS%') LOOP
    EXECUTE IMMEDIATE 'ALTER DATABASE DATAFILE ''' || f.file_name || ''' AUTOEXTEND ON MAXSIZE 4G';
  END LOOP;
END;
/

ALTER SESSION SET CONTAINER = ORCLPDB1;

DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM dba_tablespaces WHERE tablespace_name = 'SALTATION_DATA';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLESPACE saltation_data DATAFILE '/opt/oracle/oradata/ORCLCDB/ORCLPDB1/saltation_data01.dbf' SIZE 1G AUTOEXTEND ON NEXT 512M MAXSIZE UNLIMITED]';
  END IF;
  SELECT COUNT(*) INTO v_cnt FROM dba_tablespaces WHERE tablespace_name = 'OUTBOX_TS';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLESPACE outbox_ts DATAFILE '/opt/oracle/oradata/ORCLCDB/ORCLPDB1/outbox01.dbf' SIZE 256M AUTOEXTEND ON NEXT 128M MAXSIZE 4G]';
  END IF;
  SELECT COUNT(*) INTO v_cnt FROM dba_users WHERE username = 'SALTATION';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE USER saltation IDENTIFIED BY "TempInit_0" DEFAULT TABLESPACE saltation_data QUOTA UNLIMITED ON saltation_data QUOTA UNLIMITED ON outbox_ts]';
  END IF;
END;
/

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW, CREATE PROCEDURE TO saltation;
EXIT
