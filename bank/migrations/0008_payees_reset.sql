-- 0008_payees_reset: payees, password resets and outbound SMS messages.

CREATE TABLE payee (
  payee_id       NUMBER(12)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id    NUMBER(12)     NOT NULL REFERENCES customer (customer_id),
  bank_code      VARCHAR2(3)    NOT NULL,
  account_no     VARCHAR2(16)   NOT NULL,
  holder_name    VARCHAR2(60 CHAR) NOT NULL,
  alias          VARCHAR2(40 CHAR),
  registered_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  channel        VARCHAR2(10)   NOT NULL,
  session_id     VARCHAR2(26),
  deleted_at     TIMESTAMP(6) WITH TIME ZONE,
  recorded_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX payee_customer_ix ON payee (customer_id, registered_at)
/
CREATE UNIQUE INDEX payee_active_uk ON payee (
  CASE WHEN deleted_at IS NULL THEN customer_id END,
  CASE WHEN deleted_at IS NULL THEN bank_code END,
  CASE WHEN deleted_at IS NULL THEN account_no END
)
/
CREATE TABLE password_reset (
  reset_id      NUMBER(12)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id   NUMBER(12)     NOT NULL REFERENCES customer (customer_id),
  code_hash     VARCHAR2(200)  NOT NULL,
  issued_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  expires_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  used_at       TIMESTAMP(6) WITH TIME ZONE,
  failed_count  NUMBER(3)      DEFAULT 0 NOT NULL,
  recorded_at   TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX password_reset_customer_ix ON password_reset (customer_id, issued_at)
/
CREATE TABLE sms_outbox (
  sms_id       NUMBER(15)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone        VARCHAR2(20)   NOT NULL,
  message      VARCHAR2(200 CHAR) NOT NULL,
  occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  recorded_at  TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX sms_outbox_phone_ix ON sms_outbox (phone, sms_id)
