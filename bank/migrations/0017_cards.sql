-- 0017_cards: synthetic debit cards and authorization attributes (no posting route).
CREATE TABLE card (
  card_id NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_no VARCHAR2(16) NOT NULL CONSTRAINT card_no_uk UNIQUE,
  account_id NUMBER(12) NOT NULL REFERENCES account (account_id),
  status VARCHAR2(7) NOT NULL CHECK (status IN ('ACTIVE', 'BLOCKED')),
  issued_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  recorded_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT card_no_ck CHECK (REGEXP_LIKE(card_no, '^0000[0-9]{12}$', 'c'))
)
/
CREATE INDEX card_account_ix ON card (account_id)
/
CREATE TABLE card_authorization (
  request_id VARCHAR2(26) PRIMARY KEY REFERENCES transaction_request (request_id),
  card_id NUMBER(12) REFERENCES card (card_id),
  card_no_sent VARCHAR2(16) NOT NULL,
  krw_amount NUMBER(15,0) NOT NULL CHECK (krw_amount BETWEEN 1 AND 999999999999),
  currency VARCHAR2(3) NOT NULL CHECK (currency IN ('KRW', 'USD', 'EUR', 'JPY', 'CNY')),
  original_amount NUMBER(15,0) NOT NULL CHECK (original_amount > 0),
  merchant_name VARCHAR2(60 CHAR) NOT NULL,
  mcc CHAR(4) NOT NULL CHECK (REGEXP_LIKE(mcc, '^[0-9]{4}$', 'c')),
  country CHAR(2) NOT NULL,
  entry_mode VARCHAR2(9) NOT NULL CHECK (entry_mode IN ('in_person', 'online')),
  latitude NUMBER(8,6) CHECK (latitude BETWEEN -90 AND 90),
  longitude NUMBER(9,6) CHECK (longitude BETWEEN -180 AND 180),
  recorded_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT card_authorization_coords_ck CHECK (
    (entry_mode = 'online' AND latitude IS NULL AND longitude IS NULL) OR
    (entry_mode = 'in_person' AND latitude IS NOT NULL AND longitude IS NOT NULL)
  )
)
/
CREATE INDEX card_authorization_card_ix ON card_authorization (card_id)
/
DECLARE
BEGIN
  FOR c IN (SELECT constraint_name FROM user_constraints
            WHERE table_name = 'TRANSFER' AND constraint_type = 'C'
              AND UPPER(search_condition_vc) LIKE '%KIND%'
              AND REGEXP_LIKE(search_condition_vc, '(^|[^[:alnum:]_])IN[[:space:]]*\(', 'i')
              AND NOT REGEXP_LIKE(search_condition_vc, 'IS[[:space:]]+NOT[[:space:]]+NULL', 'i')) LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE transfer DROP CONSTRAINT "' || c.constraint_name || '"';
  END LOOP;
  EXECUTE IMMEDIATE 'ALTER TABLE transfer ADD CONSTRAINT transfer_kind_ck CHECK
    (kind IN (''transfer'', ''inbound'', ''atm_cash'', ''term_open'', ''term_close'', ''loan_disburse'', ''loan_repay'', ''card_payment''))';
END;
