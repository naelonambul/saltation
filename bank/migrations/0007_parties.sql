CREATE TABLE counterparty_client (
  counterparty_client_id  NUMBER(12)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id               VARCHAR2(40)   NOT NULL CONSTRAINT counterparty_client_uk UNIQUE,
  secret_hash             VARCHAR2(200)  NOT NULL,
  institution_code        VARCHAR2(3)    NOT NULL REFERENCES institution (institution_code),
  scope                   VARCHAR2(10)   NOT NULL CHECK (scope IN ('oob', 'card')),
  recorded_at             TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE TABLE counterparty (
  counterparty_id    NUMBER(12)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  counterparty_type  VARCHAR2(20)   NOT NULL CHECK (counterparty_type IN ('EMPLOYER', 'MERCHANT', 'INDIVIDUAL')),
  industry_code      VARCHAR2(10),
  institution_code   VARCHAR2(3)    NOT NULL REFERENCES institution (institution_code),
  account_no         VARCHAR2(16)   NOT NULL,
  name               VARCHAR2(60 CHAR) NOT NULL,
  recorded_at        TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT counterparty_account_uk UNIQUE (institution_code, account_no)
)
