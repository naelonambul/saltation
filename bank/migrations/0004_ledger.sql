-- 0004_ledger: requests, transfers, account transaction rows, daily totals,
-- the simulated clock and the outbox (in OUTBOX_TS, capped at 4 GB; spec F-36a).

CREATE TABLE transaction_request (
  request_id        VARCHAR2(26)   NOT NULL PRIMARY KEY,   -- ULID from the generator or the bank
  request_type      VARCHAR2(30)   NOT NULL,
  channel           VARCHAR2(10)   NOT NULL,
  listener          VARCHAR2(10)   NOT NULL,
  idem_scope        VARCHAR2(40)   NOT NULL,
  idem_key          VARCHAR2(40)   NOT NULL,
  request_hash      VARCHAR2(64)   NOT NULL,
  bank_tran_id      VARCHAR2(20),
  status            VARCHAR2(10)   NOT NULL CHECK (status IN ('DONE', 'REJECTED')),
  rsp_code          VARCHAR2(5)    NOT NULL,
  bank_rsp_code     VARCHAR2(3),
  response_json     VARCHAR2(4000) CHECK (response_json IS JSON),
  session_id        VARCHAR2(26),
  device_id         VARCHAR2(64),
  terminal_id       VARCHAR2(20),
  ip                VARCHAR2(45),
  region            VARCHAR2(10),
  occurred_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  recorded_at       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT transaction_request_idem_uk UNIQUE (idem_scope, idem_key)
)
/
CREATE TABLE transfer (
  transfer_id    NUMBER(15)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind           VARCHAR2(20)   NOT NULL CHECK (kind IN ('transfer', 'inbound', 'atm_cash', 'term_open', 'term_close', 'loan_disburse', 'loan_repay')),
  request_id     VARCHAR2(26)   NOT NULL REFERENCES transaction_request (request_id),
  bank_tran_id   VARCHAR2(20),
  amount         NUMBER(15)     NOT NULL CHECK (amount BETWEEN 1 AND 999999999999),
  occurred_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
)
/
CREATE TABLE account_transaction (
  tran_id                 NUMBER(15)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id              NUMBER(12)     NOT NULL REFERENCES account (account_id),
  account_sequence        NUMBER(12)     NOT NULL,
  amount                  NUMBER(15)     NOT NULL,          -- signed
  balance_after           NUMBER(15)     NOT NULL,
  inout_type              VARCHAR2(10)   NOT NULL,
  tran_type               VARCHAR2(20)   NOT NULL,
  print_content           VARCHAR2(20 CHAR),
  counterparty_bank_code  VARCHAR2(3),
  counterparty_account_no VARCHAR2(16),
  counterparty_name       VARCHAR2(60 CHAR),
  channel                 VARCHAR2(10)   NOT NULL,
  terminal_id             VARCHAR2(20),
  request_id              VARCHAR2(26)   NOT NULL REFERENCES transaction_request (request_id),
  transfer_id             NUMBER(15)     REFERENCES transfer (transfer_id),
  reversal_of             NUMBER(15)     REFERENCES account_transaction (tran_id),
  business_date           DATE           NOT NULL,
  occurred_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  recorded_at             TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT account_transaction_seq_uk UNIQUE (account_id, account_sequence)
)
/
CREATE INDEX account_transaction_date_ix ON account_transaction (account_id, business_date, account_sequence)
/
CREATE INDEX account_transaction_transfer_ix ON account_transaction (transfer_id)
/
CREATE TABLE daily_account_total (
  account_id     NUMBER(12)  NOT NULL REFERENCES account (account_id),
  business_date  DATE        NOT NULL,
  transfer_out   NUMBER(15)  DEFAULT 0 NOT NULL,
  cash_in        NUMBER(15)  DEFAULT 0 NOT NULL,
  cash_out       NUMBER(15)  DEFAULT 0 NOT NULL,
  CONSTRAINT daily_account_total_pk PRIMARY KEY (account_id, business_date)
)
/
CREATE TABLE sim_clock (
  id                CHAR(1)       DEFAULT 'X' NOT NULL PRIMARY KEY CHECK (id = 'X'),
  clock_mode        VARCHAR2(10)  NOT NULL CHECK (clock_mode IN ('BACKFILL', 'LIVE')),
  business_time     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  last_advanced_at  TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE TABLE outbox (
  event_id     VARCHAR2(26)    NOT NULL,   -- ULID, monotonic
  event_json   VARCHAR2(4000)  NOT NULL CHECK (event_json IS JSON),
  created_at   TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT outbox_pk PRIMARY KEY (event_id) USING INDEX TABLESPACE outbox_ts
) TABLESPACE outbox_ts
