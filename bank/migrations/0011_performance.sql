-- 0011_performance: query indexes and identity caches.

CREATE INDEX account_transaction_time_ix ON account_transaction (account_id, occurred_at, account_sequence)
/
CREATE INDEX account_dormancy_ix ON account (subtype, status, COALESCE(SYS_EXTRACT_UTC(last_activity_at), SYS_EXTRACT_UTC(opened_at)), account_id)
/
CREATE INDEX outbox_created_ix ON outbox (created_at) TABLESPACE outbox_ts
/
ALTER TABLE account_transaction MODIFY tran_id GENERATED BY DEFAULT AS IDENTITY (CACHE 10000)
/
ALTER TABLE transfer MODIFY transfer_id GENERATED BY DEFAULT AS IDENTITY (CACHE 10000)
/
ALTER TABLE login_attempt MODIFY attempt_id GENERATED BY DEFAULT AS IDENTITY (CACHE 1000)
/
ALTER TABLE customer MODIFY customer_id GENERATED BY DEFAULT AS IDENTITY (CACHE 1000)
/
ALTER TABLE account MODIFY account_id GENERATED BY DEFAULT AS IDENTITY (CACHE 1000)
