-- 0003_accounts: accounts, status history, Open Banking fintech numbers, tokens.

CREATE TABLE account (
  account_id          NUMBER(12)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_no          VARCHAR2(16)   NOT NULL CONSTRAINT account_no_uk UNIQUE,
  customer_id         NUMBER(12)     NOT NULL REFERENCES customer (customer_id),
  terms_id            NUMBER(10)     NOT NULL REFERENCES product_terms (terms_id),
  subtype             VARCHAR2(10)   NOT NULL CHECK (subtype IN ('DEMAND', 'TERM', 'LOAN')),
  status              VARCHAR2(10)   NOT NULL CHECK (status IN ('ACTIVE', 'DORMANT', 'CLOSED')),
  balance             NUMBER(15)     DEFAULT 0 NOT NULL CHECK (balance >= 0),
  next_sequence       NUMBER(12)     DEFAULT 1 NOT NULL,
  opened_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  last_activity_at    TIMESTAMP(6) WITH TIME ZONE,
  recorded_at         TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX account_customer_ix ON account (customer_id)
/
CREATE TABLE account_status_history (
  account_id   NUMBER(12)    NOT NULL REFERENCES account (account_id),
  from_status  VARCHAR2(10),
  to_status    VARCHAR2(10)  NOT NULL,
  reason       VARCHAR2(40)  NOT NULL,
  occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  recorded_at  TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX account_status_history_ix ON account_status_history (account_id, occurred_at)
/
CREATE TABLE fintech_account (
  fintech_use_num  VARCHAR2(24)  NOT NULL PRIMARY KEY,
  account_id       NUMBER(12)    NOT NULL CONSTRAINT fintech_account_uk UNIQUE REFERENCES account (account_id),
  user_seq_no      VARCHAR2(10)  NOT NULL
)
/
CREATE TABLE access_token (
  token_hash    VARCHAR2(64)   NOT NULL PRIMARY KEY,
  subject_type  VARCHAR2(10)   NOT NULL CHECK (subject_type IN ('CUSTOMER', 'CLIENT', 'ANALYST')),
  subject_id    NUMBER(12)     NOT NULL,
  scope         VARCHAR2(60)   NOT NULL,
  session_id    VARCHAR2(26),
  expires_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  revoked_at    TIMESTAMP(6) WITH TIME ZONE
)
