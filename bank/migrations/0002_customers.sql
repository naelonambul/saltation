-- 0002_customers: customers, credentials, devices, sessions, login attempts.
-- Business times come from the bank's simulated clock and have no default;
-- recorded_at columns are wall-clock system times.

CREATE TABLE customer (
  customer_id    NUMBER(12)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_no    VARCHAR2(12)   NOT NULL CONSTRAINT customer_no_uk UNIQUE,
  ci_hash        VARCHAR2(88)   NOT NULL CONSTRAINT customer_ci_uk UNIQUE,
  name           VARCHAR2(60 CHAR) NOT NULL,
  phone          VARCHAR2(20)   NOT NULL CONSTRAINT customer_phone_uk UNIQUE,
  address        VARCHAR2(200 CHAR),
  customer_type  VARCHAR2(20)   NOT NULL CHECK (customer_type IN ('INDIVIDUAL', 'SOLE_PROPRIETOR')),
  created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  recorded_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE TABLE customer_credential (
  customer_id          NUMBER(12)   NOT NULL PRIMARY KEY REFERENCES customer (customer_id),
  password_hash        VARCHAR2(200) NOT NULL,
  failed_count         NUMBER(3)    DEFAULT 0 NOT NULL,
  locked_until         TIMESTAMP(6) WITH TIME ZONE,
  password_changed_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
)
/
CREATE TABLE device (
  customer_id  NUMBER(12)    NOT NULL REFERENCES customer (customer_id),
  device_id    VARCHAR2(64)  NOT NULL,
  first_seen   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  last_seen    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT device_pk PRIMARY KEY (customer_id, device_id)
)
/
CREATE TABLE auth_session (
  session_id   VARCHAR2(26)   NOT NULL PRIMARY KEY,   -- ULID
  customer_id  NUMBER(12)     NOT NULL REFERENCES customer (customer_id),
  device_id    VARCHAR2(64),
  listener     VARCHAR2(10)   NOT NULL CHECK (listener IN ('PUBLIC', 'GENERATOR')),
  human        CHAR(1)        NOT NULL CHECK (human IN ('Y', 'N')),
  ip           VARCHAR2(45),
  region       VARCHAR2(10),
  started_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  last_seen    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  ended_at     TIMESTAMP(6) WITH TIME ZONE,
  end_reason   VARCHAR2(20)
)
/
CREATE INDEX auth_session_customer_ix ON auth_session (customer_id, started_at)
/
CREATE TABLE login_attempt (
  attempt_id   NUMBER(15)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone        VARCHAR2(20)   NOT NULL,
  customer_id  NUMBER(12)     REFERENCES customer (customer_id),
  outcome      VARCHAR2(20)   NOT NULL,
  device_id    VARCHAR2(64),
  ip           VARCHAR2(45),
  region       VARCHAR2(10),
  request_id   VARCHAR2(26)   NOT NULL,
  occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  recorded_at  TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX login_attempt_phone_ix ON login_attempt (phone, occurred_at)
